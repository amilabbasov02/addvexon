export const DEFAULT_LOCALE = LOCALES[0];

export function findLocale(country?: string | null): Locale {
  if (!country) return DEFAULT_LOCALE;
  return LOCALES.find((l) => l.country === country.toUpperCase()) ?? DEFAULT_LOCALE;
}

